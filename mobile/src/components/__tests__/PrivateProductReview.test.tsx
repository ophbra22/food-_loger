import AsyncStorage from '@react-native-async-storage/async-storage';
import {act,fireEvent,render,screen,waitFor} from '@testing-library/react-native';
import {useEffect} from 'react';
import {MealAnalysisReview} from '../MealAnalysisReview';
import {DraftProvider,useDraft} from '@/data/DraftProvider';
import {I18nProvider} from '@/i18n/I18nProvider';
import {manualDraft,type Draft} from '@/domain/drafts';
import {toUnifiedReview,reviewPayload} from '@/domain/unified-review';
import {openAccountStorage} from '@/storage/kv';
let mockFinish:(value:unknown)=>void;
let mockCurrent:Draft|null|undefined;
const mockSave=jest.fn((..._args:unknown[])=>new Promise(resolve=>{mockFinish=resolve;}));
const mockApi={captureSession:()=>()=>{},capabilities:async()=>({private_products:true}),nutritionReferences:async()=>({foods:[]}),savePrivateProduct:mockSave};
jest.mock('@/auth/AuthProvider',()=>({useAuth:()=>({user:{id:'alice'},api:mockApi,journal:null})}));
jest.mock('expo-router',()=>({router:{replace:jest.fn(),dismissTo:jest.fn(),back:jest.fn()},useNavigation:()=>({canGoBack:()=>true})}));
jest.mock('expo-crypto',()=>({randomUUID:()=> 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa',CryptoDigestAlgorithm:{SHA256:'SHA256'},digestStringAsync:async(_a:string,text:string)=>jest.requireActual('crypto').createHash('sha256').update(text).digest('hex')}));
const initial=toUnifiedReview({...manualDraft('food'),name:'Milk',amount:'100'});initial.analysis!.foods[0].confirmed=true;
function Harness(){const {draft,start}=useDraft();useEffect(()=>{mockCurrent=draft;},[draft]);useEffect(()=>{if(draft===null)void start(initial);},[draft,start]);return <MealAnalysisReview/>;}
beforeEach(async()=>{await AsyncStorage.clear();openAccountStorage('alice');mockSave.mockClear();});
test('pending private save locks meal corrections and logging, then restores editing without stale values',async()=>{
 await render(<I18nProvider initial="en"><DraftProvider><Harness/></DraftProvider></I18nProvider>);
 const button=await screen.findByRole('button',{name:'Save confirmed product privately'});
 const pendingPress=fireEvent.press(button);
 await waitFor(()=>expect(mockSave).toHaveBeenCalledTimes(1));
 expect(screen.getByTestId('food-weight-food').props.editable).toBe(false);
 expect(screen.getByTestId('save-analyzed-meal').props.accessibilityState.disabled).toBe(true);
 await fireEvent.changeText(screen.getByTestId('food-weight-food'),'200');
 expect(mockCurrent!.analysis!.foods[0].amount).toBe('100');
 await act(async()=>mockFinish({id:'a'.repeat(32),version:1,item:reviewPayload(initial).items[0]}));
 await pendingPress;
 await waitFor(()=>expect(screen.getByTestId('food-weight-food').props.editable).toBe(true));
 await fireEvent.changeText(screen.getByTestId('food-weight-food'),'200');
 expect(mockCurrent!.analysis!.foods[0].amount).toBe('200');
 expect(mockCurrent!.analysis!.foods[0].confirmed).toBe(false);
 expect(mockCurrent!.analysis!.foods[0].originSource?.version).toBe('1');
 await fireEvent.press(screen.getByTestId('confirm-food'));
 const nextPress=fireEvent.press(screen.getByRole('button',{name:'Save confirmed product privately'}));
 await waitFor(()=>expect(mockSave).toHaveBeenCalledTimes(2));
 expect(mockSave.mock.calls[1][0]).toBe('a'.repeat(32));
 expect(mockSave.mock.calls[1][2]).toBe(1);
 await act(async()=>mockFinish({id:'a'.repeat(32),version:2,item:reviewPayload(mockCurrent!).items[0]}));
 await nextPress;
 expect(reviewPayload(mockCurrent!).items[0].source).toMatchObject({provider:'private_product',reference_id:'a'.repeat(32),version:'2'});
 expect(mockCurrent!.analysis!.foods[0].amount).toBe('200');
});
