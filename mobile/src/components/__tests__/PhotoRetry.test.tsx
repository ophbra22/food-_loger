import {act,fireEvent,render,screen} from '@testing-library/react-native';
import MealPhoto from '@/app/(app)/add/photo';
import {I18nProvider} from '@/i18n/I18nProvider';
import {ApiError} from '@/api/errors';
const mockAnalyze=jest.fn(),mockStart=jest.fn();let mockSequence=0;
const mockNewKey=()=>String(++mockSequence).padStart(32,'0');
const mockApi={captureSession:()=>()=>{},analyzeMeal:mockAnalyze};
jest.mock('@/auth/AuthProvider',()=>({useAuth:()=>({user:{id:'owner'},api:mockApi})}));
jest.mock('@/data/DraftProvider',()=>({useDraft:()=>({start:mockStart,newKey:mockNewKey})}));
jest.mock('expo-router',()=>({router:{replace:jest.fn()},useLocalSearchParams:()=>({source:'library'})}));
jest.mock('expo-image-picker',()=>({launchImageLibraryAsync:async()=>({canceled:false,assets:[{uri:'file:///mock.jpg'}]})}));
jest.mock('@/data/images',()=>({prepareUpload:async()=>({uri:'file:///mock-upload.jpg',dispose:jest.fn()})}));
jest.mock('../Screen',()=>({Screen:({children}:any)=>children}));
jest.mock('../Header',()=>({Header:()=>null}));
beforeEach(()=>{jest.useFakeTimers();jest.clearAllMocks();mockSequence=0;mockAnalyze.mockRejectedValue(new ApiError('unavailable',{status:503,detail:'Analysis was already attempted. Reuse its cached result or start a new request.'}));});
afterEach(()=>jest.useRealTimers());
test.each(['en','he'] as const)('lost analysis result needs a deliberate new selection, with no automatic paid retry: %s',async language=>{
 await render(<I18nProvider initial={language}><MealPhoto/></I18nProvider>);
 await act(async()=>{await jest.advanceTimersByTimeAsync(350);});
 expect(mockAnalyze).not.toHaveBeenCalled();
 await fireEvent.press(screen.getByTestId('analyze-meal'));
 expect(screen.getByText(language==='en'?'A previous analysis may no longer be available. Retry keeps the same request. To request a new analysis, select the photo again; this may use another AI request.':'ייתכן שניתוח קודם כבר אינו זמין. ניסיון חוזר שומר על אותה בקשה. כדי לבקש ניתוח חדש, בחרו שוב את התמונה; פעולה זו עשויה לצרוך בקשת AI נוספת.')).toBeTruthy();
 await act(async()=>{await jest.advanceTimersByTimeAsync(60000);});
 expect(mockAnalyze).toHaveBeenCalledTimes(1);expect(mockStart).not.toHaveBeenCalled();
 await fireEvent.press(screen.getByTestId('analyze-meal'));
 expect(mockAnalyze.mock.calls[1][3]).toBe(mockAnalyze.mock.calls[0][3]);
 await fireEvent.press(screen.getByText(language==='en'?'Choose a photo':'בחירת תמונה'));
 expect(mockAnalyze).toHaveBeenCalledTimes(2);
 await fireEvent.press(screen.getByTestId('analyze-meal'));
 expect(mockAnalyze.mock.calls[2][3]).not.toBe(mockAnalyze.mock.calls[0][3]);
 expect(mockStart).not.toHaveBeenCalled();
});
